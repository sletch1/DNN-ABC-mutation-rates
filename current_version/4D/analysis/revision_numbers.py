"""Turn every revision-result JSON into LaTeX macros so that no number in the new manuscript text is typed by hand.
Each JSON file becomes a prefix; each scalar leaf becomes \\<prefix><Path><In><CamelCase>, floats to 3 significant decimals.
Missing files are skipped, and the generated macro list is written to tables/revision_numbers_index.txt for reference.
Pure standard library: runs anywhere.   python 4D/analysis/revision_numbers.py
"""
import json, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
SRC = {  # prefix -> file
    "pfc": "4D/results/p3/feature_checks.json", "psc": "4D/results/p3/sbc_selfconsistent.json", "pbase": "4D/results/p3/sbc_base.json",
    "pst": "4D/results/p3/sbc_student_t.json", "pscl": "4D/results/p3/sbc_selfconsistent_long.json", "pbl": "4D/results/p3/sbc_base_long.json",
    "prc": "4D/results/p3/recal.json", "pfour": "4D/results/p4.json", "ptwo": "4D/results/tables/p2_oracle.json",
    "pseven": "4D/results/p7_summary.json", "pval": "4D/results/validation_extended_summary.json",
    "rick": "Ricker/results/sbc_ricker.json", "rickn": "Ricker/results/npe_ricker.json", "sone": "1D/results/tables/study1_summary.json",
}
W = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}


def camel(s):
    s = re.sub(r"[0-9]", lambda m: " " + W[m.group()] + " ", str(s)); s = s.replace(">", " gt ").replace("<", " lt ").replace("=", " eq ").replace(".", " pt ")
    return "".join(w.capitalize() for w in re.split(r"[^A-Za-z]+", s) if w)


def fmt(v):
    if isinstance(v, bool): return "yes" if v else "no"
    if isinstance(v, int): return f"{v:,}".replace(",", "{,}")
    if abs(v) >= 100: return f"{v:,.0f}".replace(",", "{,}")
    if abs(v) >= 10: return f"{v:.1f}"
    if abs(v) < 0.001 and v != 0: return f"{v:.1e}"
    return f"{v:.3f}"


def walk(o, name, out):
    if isinstance(o, dict):
        for k, v in o.items():
            if k in ("rows", "samples"): continue
            walk(v, name + camel(k), out)
    elif isinstance(o, list):
        if len(o) <= 12 and all(isinstance(x, (int, float)) and not isinstance(x, bool) for x in o):
            for i, x in enumerate(o): walk(x, name + "N" + camel(str(i)), out)
    elif isinstance(o, (int, float)) and o == o: out[name] = fmt(o)


def main():
    out = {}
    for pre, f in SRC.items():
        p = ROOT / f
        if p.exists(): walk(json.load(open(p)), pre, out)
    lines = ["% generated by 4D/analysis/revision_numbers.py: do not edit"] + [f"\\providecommand{{\\{k}}}{{{v}}}" for k, v in sorted(out.items())]
    (ROOT / "tables").mkdir(exist_ok=True); (ROOT / "tables" / "revision_numbers.tex").write_text("\n".join(lines) + "\n")
    (ROOT / "tables" / "revision_numbers_index.txt").write_text("\n".join(f"{k} = {v}" for k, v in sorted(out.items())) + "\n"); print(len(out), "macros")


if __name__ == "__main__":
    main()
